  function safeText(value){
    return window.escapeHtml ? window.escapeHtml(value) : String(value).replace(/[&<>"']/g,m=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#039;'}[m]));
  }

  function renderAid(){
    const chapter=window.CHAPTERS?.[Number(window.currentChapter)-1];
    const index=Number(window._part);
    if(!chapter || !Array.isArray(chapter.sections) || index<0 || index>=chapter.sections.length)return;
    const section=chapter.sections[index];
    const mount=document.getElementById('lessonContent');
    if(!mount)return;
    mount.querySelector('[data-science-language-aid="1"]')?.remove();
    const haystack=[section.title,section.body,section.remember,section.activity,section.mistake,section.think].filter(Boolean).join(' ');
    const matches=(GLOSSARY[chapter.id]||[]).filter(([term])=>haystack.includes(term)).slice(0,3);
    if(!matches.length)return;
    const html='<div class="callout" data-science-language-aid="1" aria-label="आसान शब्द">'+
      '<b>🔬 आसान शब्द:</b> '+
      matches.map(([term,meaning],i)=>`${i?' &nbsp;•&nbsp; ':''}<span><b>${safeText(term)}</b> — ${safeText(meaning)}</span>`).join('')+
      '</div>';
    const body=mount.querySelector('.body-text');
    (body||mount.firstElementChild)?.insertAdjacentHTML('afterend',html);
  }

  function install(){
    if(typeof window.renderPart!=='function')return;
    if(window.__scienceLanguageAidInstalled)return;
    const original=window.renderPart;
    window.renderPart=function(){
      const result=original.apply(this,arguments);
      renderAid();
      return result;
    };
    window.__scienceLanguageAidInstalled=true;
    renderAid();
  }

  window.ScienceLanguageAid={glossary:GLOSSARY,install,renderAid};
  install();
  window.addEventListener('load',install,{once:true});
